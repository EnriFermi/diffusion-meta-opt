#!/bin/sh
set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PROJECT_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd)
cd "$PROJECT_ROOT"

if [ -f "$PROJECT_ROOT/mom.env" ]; then
  set -a
  . "$PROJECT_ROOT/mom.env"
  set +a
fi

ARTIFACT_ROOT="${BIG_VAE_ARTIFACT_ROOT:-$PROJECT_ROOT/artifacts/big_vae}"
export HELDOUT_ROOT="${HELDOUT_ROOT:-$ARTIFACT_ROOT/datasets/heldout/big_vae/offline_dataset}"
export HELDOUT_LOG_DIR="${HELDOUT_LOG_DIR:-$ARTIFACT_ROOT/eval/heldout/logs}"
export HELDOUT_REPORTS_DIR="${HELDOUT_REPORTS_DIR:-$ARTIFACT_ROOT/eval/heldout/reports}"
export HELDOUT_CRASHES_DIR="${HELDOUT_CRASHES_DIR:-$ARTIFACT_ROOT/eval/heldout/crashes}"
export HELDOUT_RECORDS_PER_PAIR="${HELDOUT_RECORDS_PER_PAIR:-1024}"
export HELDOUT_TARGET_SIZE_GB="${HELDOUT_TARGET_SIZE_GB:-20}"
export HELDOUT_OVERWRITE="${HELDOUT_OVERWRITE:-false}"
export HELDOUT_MAX_SEEN_SAMPLES="${HELDOUT_MAX_SEEN_SAMPLES:-0}"
export HELDOUT_X_CHUNK_SIZE_RECORDS="${HELDOUT_X_CHUNK_SIZE_RECORDS:-128}"
export HELDOUT_LOG_EVERY_SEEN_SAMPLES="${HELDOUT_LOG_EVERY_SEEN_SAMPLES:-1000}"
export HELDOUT_SAMPLE_WAIT_TIMEOUT_S="${HELDOUT_SAMPLE_WAIT_TIMEOUT_S:-1800}"
export HELDOUT_SAMPLE_WAIT_STATUS_EVERY_S="${HELDOUT_SAMPLE_WAIT_STATUS_EVERY_S:-60}"
export HELDOUT_SAMPLE_WAIT_POLL_S="${HELDOUT_SAMPLE_WAIT_POLL_S:-1}"
export HELDOUT_FAIL_ON_SAMPLE_WAIT_TIMEOUT="${HELDOUT_FAIL_ON_SAMPLE_WAIT_TIMEOUT:-true}"
export HELDOUT_COLLECTOR_PARALLEL_INFERENCE_WORKERS="${HELDOUT_COLLECTOR_PARALLEL_INFERENCE_WORKERS:-2}"
export HELDOUT_COLLECTOR_PARALLEL_MODEL_POOL_MAX_LOADED_MODELS="${HELDOUT_COLLECTOR_PARALLEL_MODEL_POOL_MAX_LOADED_MODELS:-2}"
export HELDOUT_COLLECTOR_MAX_LOADED_MODELS="${HELDOUT_COLLECTOR_MAX_LOADED_MODELS:-2}"
export HELDOUT_COLLECTOR_NUM_INFLIGHT_JOBS="${HELDOUT_COLLECTOR_NUM_INFLIGHT_JOBS:-1}"
export HELDOUT_COLLECTOR_JOBS_PER_SELECTED_MODEL="${HELDOUT_COLLECTOR_JOBS_PER_SELECTED_MODEL:-1}"
export HELDOUT_COLLECTOR_PIN_GPU="${HELDOUT_COLLECTOR_PIN_GPU:-false}"
export HELDOUT_COLLECTOR_RELEASE_DEVICE_ON_UNLOAD="${HELDOUT_COLLECTOR_RELEASE_DEVICE_ON_UNLOAD:-true}"
export HELDOUT_COLLECTOR_EMPTY_CUDA_CACHE_ON_UNLOAD="${HELDOUT_COLLECTOR_EMPTY_CUDA_CACHE_ON_UNLOAD:-true}"
export HELDOUT_COLLECTOR_RUNTIME_LOCAL_ONLY="${HELDOUT_COLLECTOR_RUNTIME_LOCAL_ONLY:-true}"
export HELDOUT_COLLECTOR_IN_MEMORY_CAPACITY_SAMPLES="${HELDOUT_COLLECTOR_IN_MEMORY_CAPACITY_SAMPLES:-1024}"
export HELDOUT_COLLECTOR_IN_MEMORY_FILL_TARGET_SAMPLES="${HELDOUT_COLLECTOR_IN_MEMORY_FILL_TARGET_SAMPLES:-1}"
export HELDOUT_COLLECTOR_IN_MEMORY_LOW_WATERMARK_SAMPLES="${HELDOUT_COLLECTOR_IN_MEMORY_LOW_WATERMARK_SAMPLES:-1}"

if [ -n "${CONDA_PREFIX:-}" ]; then
  export LD_LIBRARY_PATH="$CONDA_PREFIX/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
  exec python "$SCRIPT_DIR/build_heldout_offline_dataset.py" "$@"
fi

if command -v conda >/dev/null 2>&1; then
  CONDA_ENV_NAME="${CONDA_ENV_NAME:-onerec}"
  exec conda run -n "$CONDA_ENV_NAME" python "$SCRIPT_DIR/build_heldout_offline_dataset.py" "$@"
fi

if command -v pipenv >/dev/null 2>&1; then
  exec pipenv run python "$SCRIPT_DIR/build_heldout_offline_dataset.py" "$@"
fi

exec python "$SCRIPT_DIR/build_heldout_offline_dataset.py" "$@"
